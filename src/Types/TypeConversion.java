package Types;

public class TypeConversion {
    public static void main(String[] args) {
        char car = 'F';
        System.out.println(car);
        car+=1;
        System.out.println(car);


        char lettre;
        for(lettre = 97; lettre <= 122; lettre++) {
            System.out.println(lettre);
        }
        System.out.println(lettre);



    }
}